// Generates supabase/seed.sql from the curated universe and the NYSE calendar.
// Run: node scripts/gen-seed.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { UNIVERSE } from '../assets/js/data/universe.js';
import { tradingDays } from './nyse-calendar.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const q = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;

const symbolRows = UNIVERSE.map((u) =>
  `  (${q(u.symbol)}, ${q(u.name)}, ${q(u.type)}, ${q(u.sector)}, ${q(u.blurb)}, true, ${arr(u.collections)})`
).join(',\n');

const days = tradingDays('2026-01-01', '2028-12-31');
const calRows = days.map((r) => `  ('${r.d}', '${r.open}', '${r.close}', 'seed')`).join(',\n');

const sql = `-- Generated by scripts/gen-seed.mjs. Do not edit by hand.
-- Featured symbols (curated list students recognize) and the NYSE trading calendar 2026 to 2028.

insert into public.symbols (symbol, name, asset_type, sector, blurb, featured, collections) values
${symbolRows}
on conflict (symbol) do update set
  name = excluded.name,
  asset_type = excluded.asset_type,
  sector = excluded.sector,
  blurb = excluded.blurb,
  featured = true,
  collections = excluded.collections;

insert into public.market_calendar (d, open_time, close_time, source) values
${calRows}
on conflict (d) do nothing;
`;

writeFileSync(join(root, 'supabase', 'seed.sql'), sql);
console.log(`seed.sql written: ${UNIVERSE.length} symbols, ${days.length} trading days`);
